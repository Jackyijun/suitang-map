def chaikin(pts, it=3):
    p = np.array(pts, dtype=float)
    for _ in range(it):
        q = np.roll(p, -1, axis=0)
        p = np.concatenate([np.stack([.75 * p + .25 * q, .25 * p + .75 * q], 1).reshape(-1, 2)])
    return p

def densify(p, step=0.15):
    out = []
    for i in range(len(p)):
        a, b = p[i], p[(i + 1) % len(p)]
        n = max(1, int(np.hypot(*(b - a)) / step))
        for j in range(n): out.append(a + (b - a) * j / n)
    return np.array(out)

def outer_lonlat():
    ring = chaikin(NORTH + EAST_SOUTH, 3)
    return densify(ring)

def outer_proj(proj):
    ll = outer_lonlat()
    x, y = proj(ll[:, 0], ll[:, 1])
    return Polygon(list(zip(x, y))).buffer(0)
